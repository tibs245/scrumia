/* Team composer: three questions → modules, install commands, config.yaml.
   Pure client-side, no dependency. French pages override the strings by
   defining window.SCRUMIA_COMPOSER_STRINGS before this file loads. */
(function () {
  var S = {
    marketplace: '# add the marketplace once',
    install: '# install your composition',
    thenInit: '# then, inside the repo to set up',
    configComment: '# Generated by the composer - review, then commit',
    trackerToWrite: 'tracker: yours to write',
    implNeighbor: 'implementation: neighboring code',
    noteSolo: 'No tracker, no team: right-sized for a solo script. Specs stay current in the repo; history lives in git.',
    noteExploring: 'No tracker yet: scoping produces specs on a branch. Plug the tracker in when ideas become a backlog.',
    noteProduction: 'The full loop. You keep three touchpoints: scoping decisions, risky sign-offs, and the merge. Agents do the rest.',
    noteOtherTracker: 'The tracker slot has a defined contract - writing a Jira or Linear module is bounded work (see the docs). Until then, ticket skills degrade to text output.',
    noteOtherStack: 'No implementation module for this stack yet: the app follows neighboring code conventions - normal behavior, not a gap. The contract for writing your own fits one page.',
    notePractices: 'Practices apply app by app; where one disagrees with the implementation module, the implementation module wins.'
  };
  var over = window.SCRUMIA_COMPOSER_STRINGS || {};
  for (var k in over) S[k] = over[k];

  var SITUATIONS = {
    solo: ['scrumia-specs'],
    exploring: ['scrumia-specs', 'scrumia-discovery'],
    production: ['scrumia-specs', 'scrumia-github-project', 'scrumia-teams', 'scrumia-discovery'],
    othertracker: ['scrumia-specs', 'scrumia-discovery']
  };
  var STACK_APPS = {
    rust: { name: 'api', path: 'apps/api', type: 'backend', impl: 'scrumia-impl-rust' },
    solidjs: { name: 'web', path: 'apps/web', type: 'frontend', impl: 'scrumia-impl-solidjs' },
    other: { name: 'app', path: 'apps/app', type: 'backend', impl: null }
  };
  var PRACTICES = { tdd: 'scrumia-practice-tdd', solid: 'scrumia-practice-solid', tanstack: 'scrumia-practice-tanstack-query' };

  function read() {
    var form = document.getElementById('composer-form');
    var data = new FormData(form);
    return {
      situation: data.get('situation') || 'production',
      stacks: data.getAll('stack'),
      practices: data.getAll('practice')
    };
  }

  function compute(input) {
    var modules = ['scrumia-core'].concat(SITUATIONS[input.situation] || []);
    var apps = [], missing = [], notes = [];

    input.stacks.forEach(function (s) {
      var app = STACK_APPS[s];
      if (!app) return;
      apps.push({
        name: app.name, path: app.path, type: app.type, impl: app.impl,
        practices: input.practices.map(function (p) { return PRACTICES[p]; })
      });
      if (app.impl) modules.push(app.impl);
    });
    input.practices.forEach(function (p) { if (apps.length) modules.push(PRACTICES[p]); });

    if (input.situation === 'othertracker') { missing.push(S.trackerToWrite); notes.push(S.noteOtherTracker); }
    if (input.stacks.indexOf('other') !== -1) { missing.push(S.implNeighbor); notes.push(S.noteOtherStack); }
    if (input.situation === 'solo') notes.unshift(S.noteSolo);
    if (input.situation === 'exploring') notes.unshift(S.noteExploring);
    if (input.situation === 'production') notes.unshift(S.noteProduction);
    if (input.practices.length && apps.length) notes.push(S.notePractices);

    return { modules: dedupe(modules), apps: apps, missing: missing, notes: notes };
  }

  function dedupe(list) {
    return list.filter(function (m, i) { return list.indexOf(m) === i; });
  }

  function installBlock(modules) {
    var lines = [S.marketplace, '/plugin marketplace add tibs245/scrumia', '', S.install];
    modules.forEach(function (m) { lines.push('/plugin install ' + m + '@scrumia'); });
    lines.push('', S.thenInit, '/scrumia-core:scrumia-init');
    return lines.join('\n');
  }

  function yamlBlock(result, situation) {
    var y = [S.configComment, 'composition:'];
    y.push('  specs: scrumia-specs');
    y.push('  tracker: ' + (result.modules.indexOf('scrumia-github-project') !== -1 ? 'scrumia-github-project' : 'null'));
    y.push('  team: ' + (result.modules.indexOf('scrumia-teams') !== -1 ? 'scrumia-teams' : 'null'));
    y.push('  discovery: ' + (result.modules.indexOf('scrumia-discovery') !== -1 ? 'scrumia-discovery' : 'null'));
    y.push('  design: null');
    if (result.apps.length) {
      y.push('');
      y.push('apps:');
      result.apps.forEach(function (a) {
        y.push('  - name: ' + a.name);
        y.push('    path: ' + a.path);
        y.push('    type: ' + a.type);
        y.push('    implementation: ' + (a.impl || 'null'));
        y.push('    practices: [' + a.practices.join(', ') + ']');
      });
    }
    return y.join('\n');
  }

  function render() {
    var input = read();
    var result = compute(input);

    var chips = document.getElementById('composer-modules');
    chips.textContent = '';
    result.modules.forEach(function (m) {
      var el = document.createElement('span');
      el.className = 'chip' + (m === 'scrumia-core' ? ' chip-core' : '');
      el.textContent = m;
      chips.appendChild(el);
    });
    result.missing.forEach(function (m) {
      var el = document.createElement('span');
      el.className = 'chip chip-missing';
      el.textContent = m;
      chips.appendChild(el);
    });

    document.getElementById('composer-install').textContent = installBlock(result.modules);
    document.getElementById('composer-config').textContent = yamlBlock(result, input.situation);
    document.getElementById('composer-note').textContent = result.notes.join(' ');
  }

  document.addEventListener('DOMContentLoaded', function () {
    var form = document.getElementById('composer-form');
    if (!form) return;
    form.addEventListener('change', render);
    var copy = document.getElementById('composer-copy');
    if (copy) {
      var label = copy.textContent;
      copy.addEventListener('click', function () {
        var text = document.getElementById('composer-install').textContent;
        navigator.clipboard.writeText(text).then(function () {
          copy.textContent = copy.getAttribute('data-done') || 'Copied';
          setTimeout(function () { copy.textContent = label; }, 1600);
        });
      });
    }
    render();
  });
})();
